/**
 * Generates the plugin shaders from one shared definition, so palettes and
 * halftone curves stay in sync with the app.
 *
 *   node --experimental-strip-types plugins/generate.ts
 *
 * Writes:
 *   plugins/resolume/DitherLab.fs              ISF effect (Resolume 7.8+, VDMX, etc.)
 *   plugins/touchdesigner/dither_lab.glsl      GLSL TOP pixel shader
 *   plugins/touchdesigner/create_dither_lab.py builds a ready-to-use component in TouchDesigner
 *   plugins/resolve/DitherLab.dctl             DaVinci Resolve DCTL
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { PRESETS, hexToRgb } from "../src/engine/palettes.ts";

const root = dirname(fileURLToPath(import.meta.url));
const MAX_COLORS = 16;
const CUSTOM_SLOTS = 8;

// ------------------------------------------------------------------ shared tables

export const ALGORITHMS = [
  "Bayer 2x2", "Bayer 4x4", "Bayer 8x8", "Bayer 16x16",
  "Blue noise (IGN)", "White noise",
  "Halftone dots", "Halftone lines", "Halftone squares", "Halftone diamonds",
  "Threshold",
];
export const PALETTES = [...PRESETS.map((p) => p.name), "Custom"];
export const MATCH = ["Perceptual", "RGB", "Brightness only"];

for (const p of PRESETS) {
  if (p.colors.length > MAX_COLORS) throw new Error(`${p.name} has more than ${MAX_COLORS} colors`);
}

/** Same spot functions as src/engine/dither.ts; a, b are distances from the cell centre. */
const SPOTS: Record<string, (a: number, b: number) => number> = {
  dot: (a, b) => (a + b <= 0.5 ? (a * a + b * b) * 2 : 1 - ((0.5 - a) ** 2 + (0.5 - b) ** 2) * 2) * 0.999,
  line: (_a, b) => b * 2 * 0.999,
  square: (a, b) => Math.max(a, b) * 2 * 0.999,
  diamond: (a, b) => (a + b) * 0.999,
};

const CDF_POINTS = 16;

/** Area fraction below each spot value, sampled at CDF_POINTS + 1 knots. */
function cdfKnots(spot: (a: number, b: number) => number): number[] {
  const n = 512;
  const values: number[] = [];
  for (let i = 0; i < n; i++) {
    for (let j = 0; j < n; j++) values.push(spot(Math.abs((i + 0.5) / n - 0.5), Math.abs((j + 0.5) / n - 0.5)));
  }
  values.sort((x, y) => x - y);
  const knots: number[] = [];
  let k = 0;
  for (let s = 0; s <= CDF_POINTS; s++) {
    const v = s / CDF_POINTS;
    while (k < values.length && values[k] < v) k++;
    knots.push(k / values.length);
  }
  return knots;
}

const f = (v: number) => {
  const s = v.toFixed(6).replace(/0+$/, "");
  return s.endsWith(".") ? s + "0" : s;
};
const rgb01 = (hex: string) => hexToRgb(hex).map((v) => v / 255);

// ------------------------------------------------------------------ GLSL

function glslCdf(): string {
  return Object.entries(SPOTS)
    .map(([name, spot]) => {
      const k = cdfKnots(spot);
      const lines = k.slice(0, -1).map(
        (v, i) => `  if (s < ${f(i + 1)}) return mix(${f(v)}, ${f(k[i + 1])}, s - ${f(i)});`,
      );
      return `float cdf_${name}(float s) {\n  s *= ${f(CDF_POINTS)};\n${lines.join("\n")}\n  return ${f(k[k.length - 1])};\n}`;
    })
    .join("\n\n");
}

function glslPalettes(): string {
  const sizes = PRESETS.map((p, i) => `  if (p == ${i}) return ${p.colors.length};`).join("\n");
  const colors = PRESETS.map((p, i) => {
    const body = p.colors
      .map((c, j) => `    if (i == ${j}) return vec3(${rgb01(c).map(f).join(", ")});`)
      .join("\n");
    return `  if (p == ${i}) {\n${body}\n  }`;
  }).join("\n");
  const custom = Array.from({ length: CUSTOM_SLOTS }, (_, j) => `    if (i == ${j}) return CUSTOM_COLOR_${j + 1};`).join("\n");
  return `int paletteSize(int p) {
${sizes}
  return CUSTOM_COUNT;
}

vec3 paletteColor(int p, int i) {
${colors}
  if (p == ${PRESETS.length}) {
${custom}
  }
  return vec3(0.0);
}`;
}

/**
 * Host-neutral GLSL (ES 1.0 compatible). The host defines:
 *   SAMPLE(uv), RENDER_SIZE, TIME_SECONDS, CUSTOM_COUNT, CUSTOM_COLOR_1..8
 *   and the parameters P_ALGORITHM (int), P_PIXEL, P_STRENGTH, P_CELL, P_ANGLE,
 *   P_BRIGHTNESS, P_CONTRAST, P_GAMMA, P_SATURATION, P_INVERT (bool), P_PALETTE (int), P_MATCH (int).
 */
function glslCore(): string {
  return `// ---- Dither Lab core (generated by plugins/generate.ts; do not edit by hand) ----
// Mirrors the ordered, halftone and threshold modes of src/engine/dither.ts.
// Error diffusion processes pixels in sequence, so it has no shader version.

float dl_bit(float v, float i) { return mod(floor(v / exp2(i)), 2.0); }

// Recursive Bayer matrix by bit interleaving, normalised to [0, 1).
float dl_bayer(vec2 p, float levels) {
  float v = 0.0;
  for (int i = 0; i < 4; i++) {
    if (float(i) >= levels) break;
    float xb = dl_bit(p.x, float(i));
    float yb = dl_bit(p.y, float(i));
    v = v * 4.0 + 2.0 * abs(xb - yb) + yb;
  }
  return (v + 0.5) / exp2(levels * 2.0);
}

// Interleaved gradient noise (Jimenez 2014): cheap, evenly spread, no texture needed.
float dl_ign(vec2 p) { return fract(52.9829189 * fract(dot(p, vec2(0.06711056, 0.00583715)))); }

float dl_hash(vec2 p, float t) {
  return fract(sin(dot(p + fract(t * 0.618) * 113.0, vec2(12.9898, 78.233))) * 43758.5453);
}

${glslCdf()}

float dl_halftone(vec2 p, int kind) {
  float a = radians(P_ANGLE);
  vec2 q = mat2(cos(a), -sin(a), sin(a), cos(a)) * (p + 0.5) / max(2.0, P_CELL);
  vec2 d = abs(fract(q) - 0.5);
  if (kind == 1) return cdf_line(d.y * 2.0 * 0.999);
  if (kind == 2) return cdf_square(max(d.x, d.y) * 2.0 * 0.999);
  if (kind == 3) return cdf_diamond((d.x + d.y) * 0.999);
  float s = (d.x + d.y <= 0.5) ? dot(d, d) * 2.0 : 1.0 - dot(0.5 - d, 0.5 - d) * 2.0;
  return cdf_dot(s * 0.999);
}

${glslPalettes()}

float dl_luma(vec3 c) { return dot(c, vec3(0.2126, 0.7152, 0.0722)); }

vec3 dl_adjust(vec3 c) {
  float k = P_CONTRAST / 100.0;
  float cf = k >= 0.0 ? 1.0 / max(0.01, 1.0 - k) : 1.0 + k;
  c = clamp((c - 0.5) * cf + 0.5 + P_BRIGHTNESS / 100.0, 0.0, 1.0);
  c = pow(c, vec3(1.0 / P_GAMMA));
  float l = dl_luma(c);
  c = l + (c - l) * P_SATURATION;
  if (P_INVERT) c = 1.0 - c;
  return c;
}

vec4 ditherLab(vec2 fragCoord) {
  float px = max(1.0, P_PIXEL);
  vec2 cell = floor(fragCoord / px);
  vec2 cells = floor(RENDER_SIZE / px);
  vec4 src = SAMPLE((cell + 0.5) * px / RENDER_SIZE);
  vec3 c = dl_adjust(src.rgb);

  // Flip so the pattern's origin is top-left, as in the app.
  vec2 p = vec2(cell.x, cells.y - 1.0 - cell.y);
  int alg = P_ALGORITHM;
  float t = 0.5;
  if (alg <= 3) t = dl_bayer(mod(p, 16.0), float(alg + 1));
  else if (alg == 4) t = dl_ign(p);
  else if (alg == 5) t = dl_hash(p, TIME_SECONDS);
  else if (alg <= 9) t = dl_halftone(p, alg - 6);

  int pal = P_PALETTE;
  int n = paletteSize(pal);
  float lo = 1.0;
  float hi = 0.0;
  for (int i = 0; i < ${MAX_COLORS}; i++) {
    if (i >= n) break;
    float l = dl_luma(paletteColor(pal, i));
    lo = min(lo, l);
    hi = max(hi, l);
  }
  float spread = alg == 10 ? 0.0 : P_STRENGTH * max(32.0 / 255.0, hi - lo) / max(1.0, min(float(n - 1), 4.0));
  c += (t - 0.5) * spread;

  vec3 best = vec3(0.0);
  float bestD = 1e9;
  float cl = dl_luma(c);
  for (int i = 0; i < ${MAX_COLORS}; i++) {
    if (i >= n) break;
    vec3 pc = paletteColor(pal, i);
    vec3 d = c - pc;
    float dist;
    if (P_MATCH == 2) {
      dist = abs(cl - dl_luma(pc));
    } else if (P_MATCH == 1) {
      dist = dot(d, d);
    } else {
      float rm = (c.r + pc.r) * 0.5;
      dist = (2.0 + rm) * d.r * d.r + 4.0 * d.g * d.g + (3.0 - rm) * d.b * d.b;
    }
    if (dist < bestD) { bestD = dist; best = pc; }
  }
  return vec4(best, src.a);
}
// ---- end core ----
`;
}

