float dl_halftone(vec2 p, int kind) {
  float a = radians(P_ANGLE);
  vec2 q = mat2(cos(a), -sin(a), sin(a), cos(a)) * (p + 0.5) / max(2.0, P_CELL);
  vec2 d = abs(fract(q) - 0.5);
  if (kind == 1) return cdf_line(d.y * 2.0 * 0.999);
  if (kind == 2) return cdf_square(max(d.x, d.y) * 2.0 * 0.999);
  if (kind == 3) return cdf_diamond((d.x + d.y) * 0.999);
  float s = (d.x + d.y <= 0.5) ? dot(d, d) * 2.0 : 1.0 - dot(0.5 - d, 0.5 - d) * 2.0;
  return cdf_dot(s * 0.999);
}

