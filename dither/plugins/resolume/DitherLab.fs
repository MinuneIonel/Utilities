float dl_luma(vec3 c) { return dot(c, vec3(0.2126, 0.7152, 0.0722)); }

vec3 dl_adjust(vec3 c) {
  float k = P_CONTRAST / 100.0;
  float cf = k >= 0.0 ? 1.0 / max(0.01, 1.0 - k) : 1.0 + k;
  c = clamp((c - 0.5) * cf + 0.5 + P_BRIGHTNESS / 100.0, 0.0, 1.0);
  c = pow(c, vec3(1.0 / P_GAMMA));
  float l = dl_luma(c);
  c = l + (c - l) * P_SATURATION;
  if (P_INVERT) c = 1.0 - c;
  return c;
}

vec4 ditherLab(vec2 fragCoord) {
  float px = max(1.0, P_PIXEL);
  vec2 cell = floor(fragCoord / px);
  vec2 cells = floor(RENDER_SIZE / px);
  vec4 src = SAMPLE((cell + 0.5) * px / RENDER_SIZE);
  vec3 c = dl_adjust(src.rgb);

  // Flip so the pattern's origin is top-left, as in the app.
  vec2 p = vec2(cell.x, cells.y - 1.0 - cell.y);
  int alg = P_ALGORITHM;
  float t = 0.5;
  if (alg <= 3) t = dl_bayer(mod(p, 16.0), float(alg + 1));
  else if (alg == 4) t = dl_ign(p);
  else if (alg == 5) t = dl_hash(p, TIME_SECONDS);
  else if (alg <= 9) t = dl_halftone(p, alg - 6);

  int pal = P_PALETTE;
  int n = paletteSize(pal);
  float lo = 1.0;
  float hi = 0.0;
  for (int i = 0; i < 16; i++) {
    if (i >= n) break;
    float l = dl_luma(paletteColor(pal, i));
    lo = min(lo, l);
    hi = max(hi, l);
  }
  float spread = alg == 10 ? 0.0 : P_STRENGTH * max(32.0 / 255.0, hi - lo) / max(1.0, min(float(n - 1), 4.0));
  c += (t - 0.5) * spread;

  vec3 best = vec3(0.0);
  float bestD = 1e9;
  float cl = dl_luma(c);
  for (int i = 0; i < 16; i++) {
    if (i >= n) break;
    vec3 pc = paletteColor(pal, i);
    vec3 d = c - pc;
    float dist;
    if (P_MATCH == 2) {
      dist = abs(cl - dl_luma(pc));
    } else if (P_MATCH == 1) {
      dist = dot(d, d);
    } else {
      float rm = (c.r + pc.r) * 0.5;
      dist = (2.0 + rm) * d.r * d.r + 4.0 * d.g * d.g + (3.0 - rm) * d.b * d.b;
    }
    if (dist < bestD) { bestD = dist; best = pc; }
  }
  return vec4(best, src.a);
}
// ---- end core ----

void main() {
  gl_FragColor = ditherLab(gl_FragCoord.xy);
}
