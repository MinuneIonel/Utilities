// Error diffusion processes pixels in sequence, so it has no shader version.

float dl_bit(float v, float i) { return mod(floor(v / exp2(i)), 2.0); }

// Recursive Bayer matrix by bit interleaving, normalised to [0, 1).
float dl_bayer(vec2 p, float levels) {
  float v = 0.0;
  for (int i = 0; i < 4; i++) {
    if (float(i) >= levels) break;
    float xb = dl_bit(p.x, float(i));
    float yb = dl_bit(p.y, float(i));
    v = v * 4.0 + 2.0 * abs(xb - yb) + yb;
  }
  return (v + 0.5) / exp2(levels * 2.0);
}

// Interleaved gradient noise (Jimenez 2014): cheap, evenly spread, no texture needed.
float dl_ign(vec2 p) { return fract(52.9829189 * fract(dot(p, vec2(0.06711056, 0.00583715)))); }

float dl_hash(vec2 p, float t) {
  return fract(sin(dot(p + fract(t * 0.618) * 113.0, vec2(12.9898, 78.233))) * 43758.5453);
}

